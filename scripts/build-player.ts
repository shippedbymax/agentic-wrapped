/**
 * Dev-time only: bundles the browser player into one script and stores it as a string
 * constant, so the published CLI can inline it into the HTML file without a bundler.
 * `test/player-bundle.test.ts` fails when the stored bundle is out of date.
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const ENTRY_PATH = fileURLToPath(new URL('../src/renderers/video/player/main.ts', import.meta.url));
const OUTPUT_PATH = fileURLToPath(
  new URL('../src/renderers/video/player-bundle.generated.ts', import.meta.url),
);

export async function bundlePlayer(): Promise<string> {
  const result = await build({
    entryPoints: [ENTRY_PATH],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'es2020',
    minify: true,
    legalComments: 'none',
  });
  const script = result.outputFiles[0]?.text;
  if (!script) throw new Error('esbuild produced no output');
  return script.trim();
}

export function toModuleSource(script: string): string {
  return `// Generated by \`npm run build:player\`. Do not edit.\nexport const PLAYER_SCRIPT = ${JSON.stringify(script)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const script = await bundlePlayer();
  await writeFile(OUTPUT_PATH, toModuleSource(script));
  console.log(`Wrote player bundle (${(script.length / 1024).toFixed(1)} KB).`);
}
